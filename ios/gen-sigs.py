#!/usr/bin/env python3
"""Writes fk_sigs.c: for every wasm table index the VM's Module.fkSig() value
(number of parameters + 16 * result kind, -1 unknown) read from the .wasm."""
import sys

d = open(sys.argv[1], 'rb').read()
pos = 8

def leb(signed=False):
    global pos
    r = s = 0
    while True:
        b = d[pos]; pos += 1
        r |= (b & 0x7f) << s; s += 7
        if not b & 0x80:
            break
    if signed and b & 0x40:
        r -= 1 << s
    return r

def name():
    global pos
    n = leb(); v = d[pos:pos+n].decode(); pos += n
    return v

types, func_types, elem = [], [], []
imported = 0
KIND = {0x7f: 1, 0x7e: 2, 0x7d: 3, 0x7c: 4}
while pos < len(d):
    sid = d[pos]; pos += 1
    size = leb(); end = pos + size
    if sid == 1:
        for _ in range(leb()):
            assert d[pos] == 0x60; pos += 1
            n = leb(); params = list(d[pos:pos+n]); pos += n
            n = leb(); res = list(d[pos:pos+n]); pos += n
            types.append((params, res))
    elif sid == 2:
        for _ in range(leb()):
            name(); name(); k = d[pos]; pos += 1
            if k == 0:
                func_types.append(leb()); imported += 1
            elif k == 1: pos += 1; f = leb(); leb(); (leb() if f & 1 else None)
            elif k == 2: f = leb(); leb(); (leb() if f & 1 else None)
            elif k == 3: pos += 2
    elif sid == 3:
        for _ in range(leb()):
            func_types.append(leb())
    elif sid == 9:
        for _ in range(leb()):
            flags = leb()
            assert flags == 0, 'element segment form %d' % flags
            assert d[pos] == 0x41; pos += 1
            off = leb(True); assert d[pos] == 0x0b; pos += 1
            for i in range(leb()):
                elem.append((off + i, leb()))
    pos = end

size = max(i for i, _ in elem) + 1
out = [-1] * size
for i, f in elem:
    params, res = types[func_types[f]]
    kind = KIND[res[0]] if res else 0
    out[i] = len(params) + 16 * kind
with open(sys.argv[2], 'w') as f:
    f.write('/* generated by gen-sigs.py */\nconst int fk_sig_count = %d;\nconst short fk_sig_table[] = {\n' % size)
    for i in range(0, size, 16):
        f.write(','.join(str(v) for v in out[i:i+16]) + ',\n')
    f.write('};\n')
print('%d table entries, %d typed' % (size, sum(1 for v in out if v >= 0)))
